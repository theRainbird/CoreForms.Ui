namespace OldSchoolForms.Ui.Controls.Advanced;

/// <summary>
/// Defines the display mode of the CalendarView control.
/// </summary>
public enum CalendarViewType
{
    /// <summary>
    /// Displays an entire month in a grid layout.
    /// </summary>
    Month,

    /// <summary>
    /// Displays a single week with time slots.
    /// </summary>
    Week,

    /// <summary>
    /// Displays a single day with time slots.
    /// </summary>
    Day
}
