namespace OldSchoolForms.Ui.Controls.Advanced;

/// <summary>
/// Specifies the alignment of content within a DataGridView cell.
/// </summary>
public enum DataGridViewContentAlignment
{
    /// <summary>
    /// Content is aligned to the left.
    /// </summary>
    Left,

    /// <summary>
    /// Content is centered.
    /// </summary>
    Center,

    /// <summary>
    /// Content is aligned to the right.
    /// </summary>
    Right
}
