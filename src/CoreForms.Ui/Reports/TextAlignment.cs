namespace CoreForms.Ui.Reports;

/// <summary>
/// Specifies the alignment of text content within a report control.
/// </summary>
public enum TextAlignment
{
    /// <summary>
    /// Content is aligned to the left.
    /// </summary>
    Left,

    /// <summary>
    /// Content is centered.
    /// </summary>
    Center,

    /// <summary>
    /// Content is aligned to the right.
    /// </summary>
    Right
}
