namespace CoreForms.Ui.Core;

/// <summary>
/// Specifies how content is aligned within a control.
/// </summary>
public enum ContentAlignment
{
    /// <summary>
    /// Content is aligned to the top-left.
    /// </summary>
    TopLeft = 0,

    /// <summary>
    /// Content is aligned to the top-center.
    /// </summary>
    TopCenter = 1,

    /// <summary>
    /// Content is aligned to the top-right.
    /// </summary>
    TopRight = 2,

    /// <summary>
    /// Content is aligned to the middle-left.
    /// </summary>
    MiddleLeft = 3,

    /// <summary>
    /// Content is centered both horizontally and vertically.
    /// </summary>
    MiddleCenter = 4,

    /// <summary>
    /// Content is aligned to the middle-right.
    /// </summary>
    MiddleRight = 5,

    /// <summary>
    /// Content is aligned to the bottom-left.
    /// </summary>
    BottomLeft = 6,

    /// <summary>
    /// Content is aligned to the bottom-center.
    /// </summary>
    BottomCenter = 7,

    /// <summary>
    /// Content is aligned to the bottom-right.
    /// </summary>
    BottomRight = 8
}
