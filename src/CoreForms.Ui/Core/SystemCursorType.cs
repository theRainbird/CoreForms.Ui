namespace CoreForms.Ui.Core;

/// <summary>
/// Standard system cursor types supported by the platform.
/// </summary>
public enum SystemCursorType
{
    /// <summary>
    /// Default platform cursor (usually an arrow).
    /// </summary>
    Default,

    /// <summary>
    /// Arrow cursor.
    /// </summary>
    Arrow,

    /// <summary>
    /// Text selection I-beam cursor.
    /// </summary>
    IBeam,

    /// <summary>
    /// Crosshair cursor.
    /// </summary>
    Crosshair,

    /// <summary>
    /// Hand cursor.
    /// </summary>
    Hand,

    /// <summary>
    /// Horizontal resize cursor (left-right arrows).
    /// </summary>
    SizeWE,

    /// <summary>
    /// Vertical resize cursor (up-down arrows).
    /// </summary>
    SizeNS,

    /// <summary>
    /// Omni-directional resize cursor.
    /// </summary>
    SizeAll,

    /// <summary>
    /// Not-allowed cursor.
    /// </summary>
    NotAllowed
}
